const SETTINGS_FILE         = join(import.meta.dir, 'settings.json')

// Cached: readSettings() reads like a cheap accessor, which is how it ended up
// inside the per-slide export loop. It is a readFileSync + JSON.parse.
let settingsCache: Record<string, any> | null = null
function readSettings(): Record<string, any> {
  if (settingsCache) return settingsCache
  try { settingsCache = JSON.parse(readFileSync(SETTINGS_FILE, 'utf8')) } catch { settingsCache = {} }
  return settingsCache!
}
function writeSettings(data: Record<string, any>) {
  const merged = { ...readSettings(), ...data }
  settingsCache = null
  writeFileSync(SETTINGS_FILE, JSON.stringify(merged, null, 2))
}

/** The audio bed to lay under a video: what the caller asked for, else the
 *  configured default, else nothing. Never guesses at a file on disk. */
function resolveAudio(requested?: string): string | undefined {
  const explicit = requested ? resolveMediaPath(requested) : null
  if (explicit) return explicit
  const configured = readSettings().audioPath
  if (!configured) return undefined
  const abs = expandPath(configured.startsWith('/') || configured.startsWith('~')
    ? configured : join(import.meta.dir, configured))
  return existsSync(abs) ? abs : undefined
}

/** Export folder name for a carousel title. Mirrored by slugify() in App.tsx. */
function slugFromTitle(title: string): string {
  return (title || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'carousel'
}

/** Creator handle shown on CTA slides and in the platform preview mockups. */
function creatorHandle(): string {
  const h = (readSettings().handle || '@yourhandle').trim()
  return h.startsWith('@') ? h : `@${h}`
}

