// Where finished carousels land. Defaults to a folder inside the app so a fresh
// clone works with no configuration; point it somewhere else (e.g. a content
// repo) with CAROUSEL_EXPORT_DIR or `exportDir` in settings.json.
function exportDir(): string {
  const configured = process.env.CAROUSEL_EXPORT_DIR || readSettings().exportDir
  if (!configured) return join(import.meta.dir, 'exports')
  return expandPath(configured)
}

/** Content type for a served media file. One source of truth: every route
 *  that streams from disk had its own guess, and each defaulted to an image
 *  type, so an mp4 came back labelled as a picture and would not play. */
function mediaType(name: string): string {
  const ext = name.slice(name.lastIndexOf('.')).toLowerCase()
  return ({
    '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
    '.webp': 'image/webp', '.gif': 'image/gif',
    '.mp4': 'video/mp4', '.mov': 'video/quicktime', '.webm': 'video/webm',
    '.pdf': 'application/pdf',
  } as Record<string, string>)[ext] ?? 'application/octet-stream'
}

/** `~` in a configured path means the user's home directory. */
function expandPath(p: string): string {
  return p.startsWith('~')
    ? join(homedir(), p.slice(1).replace(/^[/\\]/, ''))
    : resolve(p)
}
